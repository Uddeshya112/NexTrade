ALTER TABLE app_user
    ADD COLUMN IF NOT EXISTS suspension_reason VARCHAR(500),
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;

CREATE TABLE IF NOT EXISTS instrument (
    id BIGSERIAL PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    symbol VARCHAR(20) NOT NULL UNIQUE,
    isin VARCHAR(12) UNIQUE,
    name VARCHAR(255) NOT NULL,
    exchange VARCHAR(20) NOT NULL DEFAULT 'NSE',
    currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    lot_size INTEGER NOT NULL DEFAULT 1,
    tick_size NUMERIC(19,4) NOT NULL DEFAULT 0.05,
    tick_size_tick NUMERIC(19,4) DEFAULT 0.05,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    meta_json JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS portfolio (
    id BIGSERIAL PRIMARY KEY,
    user_id UUID NOT NULL UNIQUE REFERENCES app_user(id),
    realized_pnl NUMERIC(19,4) NOT NULL DEFAULT 0,
    realized_pnl_currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT
);

CREATE TABLE IF NOT EXISTS holding (
    id BIGSERIAL PRIMARY KEY,
    portfolio_id BIGINT NOT NULL REFERENCES portfolio(id),
    instrument_id BIGINT NOT NULL REFERENCES instrument(id),
    quantity NUMERIC(19,4) NOT NULL DEFAULT 0,
    available_quantity NUMERIC(19,4) NOT NULL DEFAULT 0,
    reserved_quantity NUMERIC(19,4) NOT NULL DEFAULT 0,
    avg_buy_price NUMERIC(19,4) NOT NULL DEFAULT 0,
    avg_buy_price_tick NUMERIC(19,4) NOT NULL DEFAULT 0.05,
    realized_pnl NUMERIC(19,4) NOT NULL DEFAULT 0,
    realized_pnl_currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_holding_portfolio_instrument UNIQUE (portfolio_id, instrument_id)
);
